"""The Challenge 3 query set — six Cypher queries, one per assignment requirement.

Every query is **parameterised**, never built by string interpolation and never
generated by a model. The schema is known and the questions are fixed, so a
text-to-Cypher step would add a failure mode to something that has none. That is the
same reasoning that retired text-to-SQL in Challenge 2, and building this graph gave
it three more worked examples: a string timestamp silently concatenating with a
duration, a `count {}` subquery collapsing to 1 beside an aggregate, and an unbound
relationship drawing disconnected nodes. None raised an error. A malformed graph
query tends to return a wrong answer rather than fail, so a model generating Cypher
has nothing to correct against.

Run one:   PYTHONPATH=src .venv/bin/python -m murphy.kg_queries q5
Run all:   PYTHONPATH=src .venv/bin/python -m murphy.kg_queries
"""

from __future__ import annotations

import argparse

from . import kg

# --------------------------------------------------------------------------------
# Q1 / Q2 -- creation. These are the statements the loader runs; they are quoted here
# so the slides can show the real thing rather than a re-typed approximation.
# --------------------------------------------------------------------------------

Q1_CREATE_NODES = """
UNWIND $rows AS row
MERGE (f:Flight {flight_id: row.flight_id})
SET f += row
""".strip()

Q2_CREATE_RELATIONSHIPS = """
UNWIND $rows AS row
MATCH (a:Flight {flight_id: row.from_id})
MATCH (b:Flight {flight_id: row.to_id})
MERGE (a)-[r:PRECEDES]->(b)
SET r.gap_min = row.gap_min
""".strip()

# MERGE rather than CREATE, on a key backed by a uniqueness constraint, is what makes
# the load idempotent -- re-running leaves the same graph instead of a doubled one.

Q1_VERIFY = """
MATCH (n) UNWIND labels(n) AS label
RETURN label, count(*) AS nodes ORDER BY nodes DESC
"""

Q2_VERIFY = """
MATCH ()-[r]->() RETURN type(r) AS relationship, count(*) AS edges ORDER BY edges DESC
"""

# --------------------------------------------------------------------------------
# Q3 -- MATCH: find entities
# --------------------------------------------------------------------------------

Q3_FIND_ITINERARY = """
MATCH (t:Traveler)-[:BOOKED]->(i:Itinerary)-[leg:CONTAINS]->(f:Flight)
MATCH (f)-[:DEPARTS_FROM]->(from:Airport)
MATCH (f)-[:ARRIVES_AT]->(to:Airport)
WHERE i.itinerary_id = $itinerary_id
RETURN leg.leg_order        AS leg,
       f.flight_id          AS flight,
       from.iata            AS from,
       to.iata              AS to,
       f.sched_dep_utc      AS scheduled_departure,
       f.outcome_arr_delay_min AS arrived_late_by,
       t.arrive_by_utc      AS traveler_deadline
ORDER BY leg
"""

# --------------------------------------------------------------------------------
# Q4 -- traverse a relationship: one flight to its aircraft, and that aircraft's day
# --------------------------------------------------------------------------------

Q4_AIRCRAFT_DAY = """
MATCH (:Flight {flight_id: $flight_id})<-[:FLIES]-(ac:Aircraft)
MATCH (ac)-[:FLIES]->(leg:Flight)
MATCH (leg)-[:DEPARTS_FROM]->(from:Airport)
MATCH (leg)-[:ARRIVES_AT]->(to:Airport)
RETURN ac.tail_number AS aircraft,
       leg.flight_id  AS flight,
       from.iata      AS from,
       to.iata        AS to,
       leg.outcome_arr_delay_min        AS arr_delay,
       leg.outcome_delay_carrier_min    AS carrier_delay,
       leg.outcome_delay_late_aircraft_min AS late_aircraft_delay
ORDER BY leg.sched_dep_utc
"""

# Path-returning form for the browser. Returning the relationship, not just its
# endpoints, is what makes the edges render -- otherwise the aircraft appears orphaned.
Q4_VISUAL = """
MATCH p1 = (ac:Aircraft {tail_number: $tail_number})-[:FLIES]->(:Flight)
OPTIONAL MATCH p2 = (:Flight)<-[:FLIES]-(ac)-[:FLIES]->(:Flight)
RETURN p1, p2
"""

# --------------------------------------------------------------------------------
# Q5 -- multi-hop. The rotation cascade: what breaks downstream, and does the data
# independently agree that it was this aircraft's fault?
# --------------------------------------------------------------------------------

Q5_ROTATION_CASCADE = """
MATCH path = (origin:Flight {flight_id: $flight_id})-[:PRECEDES*1..4]->(later:Flight)
RETURN [n IN nodes(path) | n.flight_id]  AS chain,
       length(path)                      AS hops,
       later.flight_id                   AS downstream_flight,
       later.outcome_arr_delay_min       AS arrived_late_by,
       later.outcome_delay_late_aircraft_min AS blamed_on_late_aircraft
ORDER BY later.sched_dep_utc
"""

Q5_VISUAL = """
MATCH path = (:Flight {flight_id: $flight_id})-[:PRECEDES*1..4]->(:Flight)
RETURN path
"""

# --------------------------------------------------------------------------------
# Q6 -- the project-specific query. Correlated failure.
#
# Challenge 2's report named this as a limitation: "flight legs are scored
# independently, so correlated delay at a shared hub is currently invisible." It is
# invisible in a row store because answering it needs a self-join nobody would write.
# Here it is two hops.
# --------------------------------------------------------------------------------

Q6_CORRELATED_FAILURE = """
MATCH (i:Itinerary {itinerary_id: $itinerary_id})-[:CONTAINS]->(booked:Flight)
MATCH (booked)-[:DEPARTS_FROM]->(hub:Airport)
MATCH (booked)-[:ARRIVES_AT]->(final:Airport {iata: i.final_dest})
MATCH (alternative:Flight)-[:DEPARTS_FROM]->(hub)
MATCH (alternative)-[:ARRIVES_AT]->(final)
OPTIONAL MATCH (ac:Aircraft)-[:FLIES]->(alternative)
OPTIONAL MATCH (upstream:Flight)-[:PRECEDES]->(alternative)
RETURN hub.iata              AS leaving_from,
       final.iata            AS heading_to,
       alternative.flight_id AS option,
       alternative.flight_id = booked.flight_id AS is_my_booked_flight,
       ac.tail_number        AS aircraft,
       upstream.flight_id    AS that_aircraft_came_in_on,
       upstream.outcome_arr_delay_min    AS already_late_by,
       alternative.outcome_arr_delay_min AS option_arrived_late_by
ORDER BY alternative.sched_dep_utc
"""

# Why this is the "why a graph" query, and why it was rewritten once.
#
# The first version asked whether an alternative shared *my* inbound aircraft. That
# almost never fires -- an inbound is frequently the last leg of its aircraft's day,
# so the answer is a column of False.
#
# The question that matters is whether the alternative's **own** aircraft is already
# running late somewhere upstream, because switching onto a plane that is itself stuck
# is not an escape. Answering it means walking backwards along PRECEDES from every
# candidate, which is a self-join nobody writes in SQL and two hops here.
#
# itin-no-escape is the case: nine ATL->EWR options on 19 July, every one flown by an
# aircraft already 45+ minutes late, average arrival +267 minutes. A forecaster scoring
# legs independently shows nine options each carrying "some risk" and misses that they
# all fail for the same reason -- exactly the limitation the Challenge 2 report named.

Q6_VISUAL = """
MATCH (i:Itinerary {itinerary_id: $itinerary_id})-[:CONTAINS]->(booked:Flight)
MATCH (booked)-[:DEPARTS_FROM]->(hub:Airport)
MATCH (booked)-[:ARRIVES_AT]->(final:Airport {iata: i.final_dest})
MATCH p1 = (alternative:Flight)-[:DEPARTS_FROM]->(hub)
MATCH p2 = (alternative)-[:ARRIVES_AT]->(final)
OPTIONAL MATCH p3 = (:Flight)-[:PRECEDES]->(alternative)
RETURN p1, p2, p3
"""

# --------------------------------------------------------------------------------
# Connection feasibility -- the CONNECTS_TO that is derived rather than stored (S3).
# Materialising it would have cost 493,824 edges on one day against a 400,000 cap,
# and a connection is a question about time rather than a fact.
# --------------------------------------------------------------------------------

CONNECTION_FEASIBILITY = """
MATCH (a:Flight {flight_id: $flight_id})-[:ARRIVES_AT]->(hub:Airport)
MATCH (b:Flight)-[:DEPARTS_FROM]->(hub)
MATCH (b)-[:ARRIVES_AT]->(onward:Airport)
WHERE b.sched_dep_utc >= a.sched_arr_utc + duration({minutes: $min_connection})
  AND b.sched_dep_utc <= a.sched_arr_utc + duration({hours: $max_hours})
  AND b.carrier = a.carrier
RETURN b.flight_id AS onward_flight,
       hub.iata    AS hub,
       onward.iata AS onward_to,
       duration.between(a.sched_arr_utc, b.sched_dep_utc).minutes AS scheduled_slack_min,
       duration.between(a.sched_arr_utc, b.sched_dep_utc).minutes
         - a.outcome_arr_delay_min AS slack_after_inbound_delay,
       EXISTS { (a)-[:PRECEDES]->(b) } AS same_aircraft
ORDER BY scheduled_slack_min
"""


# --------------------------------------------------------------------------------
# The Documented tier, and the shape GraphRAG will use next stage.
#
# The graph supplies the keys that make a document lookup correct: which carrier
# operated the flight, how late it was, and whether the cause was within the
# carrier's control. Ask a vector store "am I owed a hotel?" with none of that and it
# returns whichever clause embeds nearest. Ask it with these keys and the retrieval
# is about *this* traveller. No retrieval is wired up in this challenge -- the point
# here is that the keys exist and discriminate.
# --------------------------------------------------------------------------------

POLICY_FOR_MY_DISRUPTION = """
MATCH (i:Itinerary {itinerary_id: $itinerary_id})-[:CONTAINS]->(f:Flight)
MATCH (f)-[:INSTANCE_OF]->(:Service)-[:OPERATED_BY]->(airline:Airline)
MATCH (airline)-[:PUBLISHES]->(clause:PolicyClause)
WITH f, airline, clause,
     f.outcome_arr_delay_min / 60.0 AS hours_late,
     coalesce(f.outcome_delay_carrier_min, 0) > 0 AS cause_was_the_airline
WHERE clause.controllable = cause_was_the_airline
  AND (clause.threshold_hours IS NULL OR hours_late >= clause.threshold_hours)
RETURN DISTINCT airline.name AS airline,
       round(hours_late * 60) AS my_delay_min,
       cause_was_the_airline  AS within_airline_control,
       clause.commitment      AS commitment,
       clause.disruption_type AS applies_to,
       clause.threshold_hours AS threshold_hours,
       clause.url             AS cited_source
ORDER BY commitment
"""

QUERIES = {
    "q1": ("R6  create nodes", Q1_VERIFY, {}),
    "q2": ("R7  create relationships", Q2_VERIFY, {}),
    "q3": ("R8  MATCH: a traveller's itinerary", Q3_FIND_ITINERARY,
           {"itinerary_id": "itin-cascade"}),
    "q4": ("R9  traverse: an aircraft's whole day", Q4_AIRCRAFT_DAY,
           {"flight_id": "2024-07-19_WN2679_HOU_MDW"}),
    "q5": ("R10 multi-hop: rotation cascade", Q5_ROTATION_CASCADE,
           {"flight_id": "2024-07-19_WN4854_LBB_DAL"}),
    "q6": ("R11 project-specific: correlated failure", Q6_CORRELATED_FAILURE,
           {"itinerary_id": "itin-no-escape"}),
    "policy": ("D7  Documented tier: what applies to my disruption",
               POLICY_FOR_MY_DISRUPTION, {"itinerary_id": "itin-no-escape"}),
    "connection": ("S3  derived connection feasibility", CONNECTION_FEASIBILITY,
                   {"flight_id": "2024-07-19_WN2679_HOU_MDW",
                    "min_connection": 45, "max_hours": 4}),
}


def run(name: str) -> list:
    _, cypher, params = QUERIES[name]
    return kg.run(cypher, **params)


def _show(name: str, limit: int = 8) -> None:
    label, cypher, params = QUERIES[name]
    print(f"\n{'=' * 78}\n{name.upper()}  {label}")
    if params:
        print(f"parameters: {params}")
    rows = kg.run(cypher, **params)
    print(f"{len(rows)} row(s)")
    if not rows:
        return
    keys = list(rows[0].keys())
    widths = {k: max(len(k), *(len(str(r[k])) for r in rows[:limit])) for k in keys}
    print("  " + "  ".join(k.ljust(widths[k]) for k in keys))
    print("  " + "  ".join("-" * widths[k] for k in keys))
    for r in rows[:limit]:
        print("  " + "  ".join(str(r[k]).ljust(widths[k]) for k in keys))
    if len(rows) > limit:
        print(f"  ... {len(rows) - limit} more")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("query", nargs="?", choices=sorted(QUERIES),
                    help="one query to run; omit to run them all")
    a = ap.parse_args()
    for name in ([a.query] if a.query else sorted(QUERIES)):
        _show(name)


if __name__ == "__main__":
    main()
